"""Does the recogniser know when it is guessing?

The matrix answers "did the mistake survive". This answers the question
the product actually depends on: when Whisper writes a word that was not
said, does it say so in the confidence?

If it does, the assessor can refuse to correct low-confidence spans and
stop teaching him mistakes he never made. If it does not, that guard is
theatre and the threshold in `app/assess/base.py` is a number with no
evidence behind it -- which is worth knowing either way, and is the
reason this is measured rather than assumed.

Method: transcribe every recording, align the transcript against the
sentence that was actually spoken, and label each transcribed word as
heard (its token appears in the reference) or invented (it does not).
Then compare the two confidence distributions.

The alignment is a bag-of-words containment check, not a proper
alignment. It undercounts: a word that was said in a different place
still counts as heard. It cannot overcount, which is the direction that
matters -- every word it calls invented really is absent from what he
said.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import statistics
import sys
from collections import Counter
from pathlib import Path

from app.asr.base import DecodeOptions
from app.asr.whisper import FasterWhisperTranscriber
from app.text import normalize
from experiments.whisper_fidelity.run import RESULTS
from experiments.whisper_fidelity.score import load_samples
from experiments.whisper_fidelity.synthesize import DEFAULT_OUT, FIXTURE


async def collect(
    audio_root: Path, samples, model_size: str, voices: list[str] | None
) -> list[dict]:
    transcriber = FasterWhisperTranscriber(model_size, decode=DecodeOptions())
    words: list[dict] = []

    for voice_dir in sorted(p for p in audio_root.iterdir() if p.is_dir()):
        if voices and voice_dir.name not in voices:
            continue
        for sample in samples:
            path = voice_dir / f"{sample.id}.wav"
            if not path.is_file():
                continue
            transcript = await transcriber.transcribe(path)
            # Counter, not a set: "the" said twice and written three times
            # leaves one occurrence unaccounted for, and it should count
            # as invented.
            remaining = Counter(normalize(sample.spoken).split())
            for word in transcript.words:
                for token in normalize(word.text).split():
                    heard = remaining[token] > 0
                    if heard:
                        remaining[token] -= 1
                    words.append(
                        {
                            "voice": voice_dir.name,
                            "model": model_size,
                            "sample": sample.id,
                            "token": token,
                            "confidence": word.confidence,
                            "heard": heard,
                        }
                    )
        print(f"{voice_dir.name}: {len(words)} words so far")
    return words


def report(words: list[dict]) -> str:
    lines = [
        "# Does the recogniser know when it is guessing?",
        "",
        "Generated by `python -m experiments.whisper_fidelity.confidence`. "
        "Do not edit by hand.",
        "",
        "Every transcribed word, labelled `heard` when its token appears in "
        "the sentence that was actually spoken and `invented` when it does "
        "not. If confidence is a usable guard, invented words sit lower.",
        "",
        "| voice | model | words | invented | median heard | median invented "
        "| overlap |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]

    grouped: dict[tuple[str, str], list[dict]] = {}
    for word in words:
        grouped.setdefault((word["voice"], word["model"]), []).append(word)

    for (voice, model), group in sorted(grouped.items()):
        scored = [w for w in group if w["confidence"] is not None]
        heard = [w["confidence"] for w in scored if w["heard"]]
        invented = [w["confidence"] for w in scored if not w["heard"]]
        if not heard or not invented:
            continue
        # How often an invented word is more confident than a heard one,
        # sampled over the cross product. 0.5 means the signal is noise.
        overlap = sum(
            1 for i in invented if i >= statistics.median(heard)
        ) / len(invented)
        lines.append(
            f"| {voice} | {model} | {len(scored)} | {len(invented)} | "
            f"{statistics.median(heard):.3f} | "
            f"{statistics.median(invented):.3f} | {overlap:.2f} |"
        )

    lines += ["", "## What a threshold would cost", "",
              "Dropping every word below a confidence floor: how many "
              "invented words it removes, and how many real ones it takes "
              "with them. Accented voices only.", "",
              "| floor | invented dropped | heard dropped |",
              "|---:|---:|---:|"]

    accented = [
        w for w in words
        if w["voice"].startswith("es-mx") and w["confidence"] is not None
    ]
    heard = [w for w in accented if w["heard"]]
    invented = [w for w in accented if not w["heard"]]
    for floor in (0.3, 0.4, 0.5, 0.55, 0.6, 0.7, 0.8):
        dropped_invented = sum(1 for w in invented if w["confidence"] < floor)
        dropped_heard = sum(1 for w in heard if w["confidence"] < floor)
        lines.append(
            f"| {floor:.2f} | {dropped_invented}/{len(invented)} "
            f"({dropped_invented / max(len(invented), 1):.0%}) | "
            f"{dropped_heard}/{len(heard)} "
            f"({dropped_heard / max(len(heard), 1):.0%}) |"
        )

    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audio", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--model", default="small.en")
    parser.add_argument("--voice", action="append")
    parser.add_argument("--out", type=Path, default=RESULTS)
    args = parser.parse_args(argv)

    words = asyncio.run(
        collect(args.audio, load_samples(FIXTURE), args.model, args.voice)
    )
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "confidence.json").write_text(
        json.dumps(words), encoding="utf-8"
    )
    (args.out / "confidence.md").write_text(report(words), encoding="utf-8")
    print(f"{len(words)} words -> {args.out / 'confidence.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
